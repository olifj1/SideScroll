#!/usr/bin/env python3
"""Bake a Project Backup export into SideScroll's built-in content.

Usage (run from the repo root, by a Claude session or on a desktop):
    python3 tools/bake_project.py path/to/SS-PROJECT-SNAPSHOT-....json

Writes:
  project-defaults-data.js  every content key from the export, read by
                            project-defaults.js whenever a device has no saved
                            value for that key
  design-doc.json           the Design Lab working document from the export

What is built in comes from storage-catalogue.json: keys with scope "content"
or "migration" are built in; everything else (local settings, play progress,
transient state, backups, stale keys) is left out. A key in the export that the
catalogue does not know is left out with a warning: classify it there first.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

DESIGN_DOC_KEY = 'sidescroll-design-doc-working-v2'
PUBLISHED_SCOPES = {'content', 'migration'}


def main(path):
    snapshot = json.loads(Path(path).read_text(encoding='utf-8'))
    if snapshot.get('schema') != 'sidescroll.project-snapshot.v1':
        sys.exit('Not a SideScroll Project Backup export.')
    entries = snapshot['storage']['localStorage']

    catalogue = json.loads((ROOT / 'storage-catalogue.json').read_text(encoding='utf-8'))['keys']
    storage, skipped, unknown = {}, [], []
    for entry in sorted(entries, key=lambda e: e['key']):
        key, value = entry['key'], entry['value']
        info = catalogue.get(key)
        if info is None:
            unknown.append(key)
        elif key == DESIGN_DOC_KEY:
            skipped.append((key, 'written to design-doc.json instead'))
        elif info['scope'] not in PUBLISHED_SCOPES:
            skipped.append((key, info['scope']))
        else:
            storage[key] = value if isinstance(value, str) else json.dumps(value)

    data = {
        'schema': 'sidescroll.project-defaults.v1',
        'exportedAt': snapshot.get('exportedAt'),
        'storage': storage,
    }
    js = ('/* GENERATED by tools/bake_project.py from a Project Backup export. Do not edit.\n'
          ' * Built-in content: project-defaults.js returns these values when a device has\n'
          ' * no saved value of its own for the key. */\n'
          'window.SIDESCROLL_PROJECT_DEFAULTS = ' + json.dumps(data, ensure_ascii=False) + ';\n')
    (ROOT / 'project-defaults-data.js').write_text(js, encoding='utf-8')

    design = next((e['value'] for e in entries if e['key'] == DESIGN_DOC_KEY), None)
    if design is not None:
        doc = json.loads(design) if isinstance(design, str) else design
        doc.pop('workingUpdated', None)
        (ROOT / 'design-doc.json').write_text(json.dumps(doc, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

    print(f'Built in {len(storage)} keys ({sum(len(v) for v in storage.values()):,} chars):')
    for key in storage:
        print('  +', key)
    print(f'Left out {len(skipped)} keys:')
    for key, why in skipped:
        print(f'  - {key}  ({why})')
    print('design-doc.json', 'updated' if design is not None else 'NOT updated (no working copy in export)')
    if unknown:
        print(f'WARNING: {len(unknown)} keys are not in storage-catalogue.json and were left out.')
        print('Classify them in the catalogue, then run this again:')
        for key in unknown:
            print('  ?', key)


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
